#!/usr/bin/env python3
"""Render committed HTML from content/posts.json using only the Python standard library.

Run: python3 scripts/build.py
Verify generated pages are current: python3 scripts/build.py --check
Serve the repository directly; visitors do not need JavaScript or a build server.
"""

import argparse
from html import escape
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
SITE = "https://www.ssdd.dev"


def load_posts():
    posts = json.loads((ROOT / "content/posts.json").read_text())
    slugs = set()
    for post in posts:
        slug = post["slug"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug) or slug in slugs:
            raise ValueError(f"Invalid or duplicate slug: {slug}")
        slugs.add(slug)
        if type(post["year"]) is not int or not 2000 <= post["year"] <= 2100:
            raise ValueError(f"Invalid year: {slug}")
        for field in ("title", "summary", "kind"):
            if not isinstance(post[field], str) or not post[field].strip():
                raise ValueError(f"Missing {field}: {slug}")
        if not post["paragraphs"] or not post["links"]:
            raise ValueError(f"Post needs a story and sources: {slug}")
        for link in post["links"]:
            parsed = urlsplit(link["url"])
            if parsed.scheme != "https" or not parsed.netloc:
                raise ValueError(f"Expected an HTTPS source: {slug}")
        if "home" in post and type(post["home"]) is not bool:
            raise ValueError(f"Invalid home flag: {slug}")
        section_ids = set()
        for section in post.get("sections", []):
            section_id = section["id"]
            if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", section_id) or section_id in section_ids:
                raise ValueError(f"Invalid or duplicate section: {slug}")
            section_ids.add(section_id)
            if not section["title"].strip() or not section["paragraphs"]:
                raise ValueError(f"Empty section: {slug}")
    home_posts = [post for post in posts if post.get("home")]
    if len(home_posts) != 1:
        raise ValueError("Exactly one homepage post is required.")
    homepage = home_posts[0]
    if not isinstance(homepage.get("timeline_intro"), str) or not homepage["timeline_intro"].strip():
        raise ValueError("Homepage needs a transition into the timeline")
    for post in posts:
        if any(slug not in slugs or slug == post["slug"] for slug in post["related"]):
            raise ValueError(f"Invalid related post: {post['slug']}")
    # File order is editorial order within a year, not a made-up publication date.
    return sorted(posts, key=lambda post: post["year"], reverse=True)


def post_url(post):
    return "/" if post.get("home") else f"/posts/{post['slug']}/"


def prose(post):
    paragraphs = "\n".join(f"<p>{escape(text)}</p>" for text in post["paragraphs"])
    sections = []
    for section in post.get("sections", []):
        section_body = "\n".join(f"<p>{escape(text)}</p>" for text in section["paragraphs"])
        sections.append(f'''<section aria-labelledby="note-{section['id']}">
          <h2 id="note-{section['id']}">{escape(section['title'])}</h2>
          {section_body}
        </section>''')
    return paragraphs + "\n" + "\n".join(sections)


def page(title, description, path, body, current="", article=False):
    header = "" if current == "home" else (ROOT / "content/header.html").read_text()

    return f'''<!DOCTYPE html>
<!-- Generated by scripts/build.py from content/. Edit the source, then regenerate. -->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{escape(title)} · Sandipsinh Rathod</title>
  <meta name="description" content="{escape(description, quote=True)}">
  <link rel="canonical" href="{SITE}{path}">
  <meta property="og:type" content="{'article' if article else 'website'}">
  <meta property="og:title" content="{escape(title, quote=True)} · Sandipsinh Rathod">
  <meta property="og:description" content="{escape(description, quote=True)}">
  <meta property="og:url" content="{SITE}{path}">
  <meta name="twitter:card" content="summary">
  <link rel="icon" href="/assets/images/favicon.ico">
  <link rel="stylesheet" href="/assets/css/base.css">
  <link rel="stylesheet" href="/assets/css/timeline.css">
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <div id="left"></div>
  <div id="center">
{header}
    <main id="main">
{body}
    </main>
  </div>
  <div id="right"></div>
</body>
</html>
'''


def year_nav(posts):
    years = list(dict.fromkeys(post["year"] for post in posts))
    links = "\n".join(f'<a href="#year-{year}">{year}</a>' for year in years)
    return f'<nav class="year-nav" aria-label="Browse by year"><span>Jump to</span>{links}</nav>'


def timeline(posts):
    sections = []
    for year in dict.fromkeys(post["year"] for post in posts):
        entries = []
        for post in (p for p in posts if p["year"] == year):
            entries.append(f'''<li>
              <a class="entry-title" href="{post_url(post)}">{escape(post['title'])}</a>
              <p class="entry-summary">{escape(post['summary'])}</p>
            </li>''')
        sections.append(f'''<section class="year-group" aria-labelledby="year-{year}">
          <h2 id="year-{year}" class="year-label">{year}</h2>
          <ul class="entries" role="list">{''.join(entries)}</ul>
        </section>''')
    return "\n".join(sections)


def home(posts):
    post = next(post for post in posts if post.get("home"))
    work = [post for post in posts if not post.get("home")]
    body = f'''      <article class="home-post" aria-labelledby="home-title">
      <div class="post-heading home-heading">
        <img class="signature-portrait" src="/assets/imgs/me_simple.png" alt="Illustrated portrait of Sandipsinh Rathod" width="112" height="112">
        <div>
          <h1 id="home-title">{escape(post['title'])}</h1>
          <p class="profile-email"><a href="mailto:sandip@ssdd.dev">sandip@ssdd.dev</a></p>
          <nav class="social-links" aria-label="Profiles">
            <a href="https://github.com/ssddOnTop">GitHub</a>
            <a href="https://www.linkedin.com/in/ssdddev">LinkedIn</a>
          </nav>
        </div>
      </div>
      <div class="prose home-prose">
        {prose(post)}
      </div>
      <nav class="reading-shortcuts" aria-label="Explore my work">
        <a href="/about/" rel="author">More about me</a> · <a href="/posts/">All posts</a>
      </nav>

      <section id="timeline" aria-label="Work by year">
        <span id="blog" class="anchor-alias"></span>
        <span id="achievements" class="anchor-alias"></span>
        <span id="selected-heading" class="anchor-alias"></span>
        <span id="timeline-heading" class="anchor-alias"></span>
        <p class="home-prose timeline-transition">{escape(post['timeline_intro'])}</p>
        {timeline(work)}
      </section>
      </article>'''
    return page(post["title"], post["summary"], "/", body, "home", article=True)


def archive(posts):
    body = f'''      <a class="back-link" href="/">← Back to home</a>
      <div class="card page-heading">
        <p class="eyebrow">The index</p>
        <h1>All posts</h1>
        <p>Long articles and short notes. Work, projects, and contributions all have a place here.</p>
      </div>
      <section aria-labelledby="archive-heading">
        <h2 id="archive-heading" class="visually-hidden">Posts by year</h2>
        {year_nav(posts)}
        {timeline(posts)}
      </section>'''
    return page("All posts", "An index of projects, contributions, and technical writing by Sandipsinh Rathod, grouped by year.", "/posts/", body, "posts")


def story(post, posts):
    paragraphs = prose(post)
    sources = "\n".join(f'<li><a href="{escape(link["url"], quote=True)}">{escape(link["label"])}</a></li>' for link in post["links"])
    if post.get("links_intro"):
        inline_links = ", ".join(f'<a href="{escape(link["url"], quote=True)}">{escape(link["label"])}</a>' for link in post["links"])
        source_block = f'<p class="post-links">{escape(post["links_intro"])} {inline_links}.</p>'
    else:
        source_block = f'''<section class="post-links" aria-labelledby="sources-heading">
          <h2 id="sources-heading">Read the source</h2>
          <ul>{sources}</ul>
        </section>'''
    by_slug = {p["slug"]: p for p in posts}
    related = "\n".join(f'<li><a href="{post_url(by_slug[slug])}">{escape(by_slug[slug]["title"])}</a> <span class="related-year">{by_slug[slug]["year"]}</span></li>' for slug in post["related"])
    body = f'''      <article class="card post">
        <a class="back-link" href="/#year-{post['year']}">← Back to {post['year']}</a>
        <div class="post-heading">
          <p class="eyebrow"><span class="post-year">{post['year']}</span> <span aria-hidden="true">/</span> {escape(post['kind'])}</p>
          <h1>{escape(post['title'])}</h1>
          <p class="standfirst">{escape(post['summary'])}</p>
        </div>
        <div class="prose">{paragraphs}</div>
        {source_block}
        <aside class="related" aria-labelledby="related-heading">
          <h2 id="related-heading">Also in this notebook</h2>
          <ul>{related}</ul>
        </aside>
      </article>'''
    return page(post["title"], post["summary"], post_url(post), body, article=True)


def render():
    posts = load_posts()
    pages = {
        "index.html": home(posts),
        "posts/index.html": archive(posts),
        "about/index.html": page(
            "About", "About Sandipsinh Rathod: backend engineering, Rust, and distributed systems.",
            "/about/", (ROOT / "content/about.html").read_text(), "about"
        ),
    }
    for post in posts:
        if not post.get("home"):
            pages[f"posts/{post['slug']}/index.html"] = story(post, posts)
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated pages differ; write nothing.")
    args = parser.parse_args()
    pages = render()
    outdated = []
    for name, text in pages.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                outdated.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if outdated:
        parser.exit(1, "Regenerate with python3 scripts/build.py:\n" + "\n".join(outdated) + "\n")
    print(f"{'Checked' if args.check else 'Built'} {len(pages)} static pages.")


if __name__ == "__main__":
    main()
